    [Fact]
    public async Task Walks_the_tree_and_reads_every_object_when_configured()
    {
        if (Spec is null)
        {
            output.WriteLine("BENGINE_TEST_ORACLE is not set; skipping.");
            return;
        }

        await WithScratchAsync(async server =>
        {
            await using (var session = await ObjectExplorer.OpenSessionAsync(server, null, null))
            {
                var run = await ScriptRunner.RunAsync(session, Setup);
                Assert.Equal(0, run.Failed);
            }

            // Every node's children and properties, a few per folder (system schemas are large).
            var failures = new List<string>();
            var visited = new List<TreeNode>();
            var queue = new Queue<TreeNode>([new TreeNode { Ref = new NodeRef { Kind = NodeKind.Server }, Label = server.Name, HasChildren = true }]);
            while (queue.Count > 0)
            {
                var node = queue.Dequeue();
                visited.Add(node);
                try
                {
                    var properties = await ObjectExplorer.GetPropertiesAsync(server, null, node.Ref);
                    Assert.False(string.IsNullOrEmpty(properties.Title));
                    if (node.Ref.Kind is NodeKind.Table or NodeKind.View or NodeKind.Function or NodeKind.Procedure or NodeKind.Package
                        or NodeKind.Trigger or NodeKind.Sequence or NodeKind.Synonym or NodeKind.Type or NodeKind.MaterializedView or NodeKind.Index
                        && node.Ref.Schema == server.Username)
                    {
                        Assert.False(string.IsNullOrEmpty(properties.Sql), $"No DDL for {node.Ref.Id}");
                    }
                }
                catch (Exception ex)
                {
                    failures.Add($"properties of {node.Ref.Id}: {ex.Message}");
                }

                if (!node.HasChildren)
                {
                    continue;
                }

                try
                {
                    var children = await ObjectExplorer.GetChildrenAsync(server, null, node.Ref);
                    var mine = node.Ref.Kind is NodeKind.SchemasFolder ? children.Where(c => c.Ref.Name == server.Username) : children;
                    foreach (var child in node.IsFolder && node.Ref.Kind != NodeKind.SchemasFolder ? mine.Take(node.Ref.Schema == server.Username ? 50 : 2) : mine)
                    {
                        queue.Enqueue(child);
                    }
                }
                catch (Exception ex)
                {
                    failures.Add($"children of {node.Ref.Id}: {ex.Message}");
                }
            }

            output.WriteLine(string.Join('\n', visited.Select(v => $"{v.Ref.Kind}: {v.Label}{(v.Count is { } c ? $" ({c})" : string.Empty)}{(v.Detail is { } d ? $"  [{d}]" : string.Empty)}")));
            output.WriteLine(string.Join('\n', failures));
            Assert.Empty(failures);
            foreach (var kind in new[] { NodeKind.Table, NodeKind.View, NodeKind.MaterializedView, NodeKind.Sequence, NodeKind.Function, NodeKind.Procedure,
                NodeKind.Package, NodeKind.Type, NodeKind.Synonym, NodeKind.Column, NodeKind.PrimaryKey, NodeKind.ForeignKey, NodeKind.UniqueConstraint,
                NodeKind.CheckConstraint, NodeKind.Index, NodeKind.Trigger, NodeKind.Catalog })
            {
                Assert.Contains(visited, v => v.Ref.Kind == kind);
            }
        });
    }

    [Fact]
    public async Task Runs_the_console_data_editor_and_tools_when_configured()
    {
        if (Spec is null)
        {
            output.WriteLine("BENGINE_TEST_ORACLE is not set; skipping.");
            return;
        }

        await WithScratchAsync(async server =>
        {
            await using var session = await ObjectExplorer.OpenSessionAsync(server, null, null);
            await ScriptRunner.RunAsync(session, Setup);

            // Console: statements split the Oracle way (a PL/SQL block keeps its END;).
            var script = "SELECT id, email, born, balance, note, created FROM customers ORDER BY id;\nBEGIN touch_customer(1); END;\n/\nSELECT shop_api.order_count(1) AS n FROM dual;";
            var statements = SqlScript.Split(script, DatabaseProvider.Oracle);
            Assert.Equal(3, statements.Count);
            var rows = await session.Query.ExecuteAllAsync(statements[0].Text);
            Assert.Equal(3, rows[0].Rows.Count);
            Assert.Equal("it's; \"quoted\"", rows[0].Rows[0][4]);
            output.WriteLine(string.Join(" | ", rows[0].Rows[0].Select(v => $"{v} ({v?.GetType().Name})")));
            await session.Query.ExecuteAllAsync(statements[1].Text);

            // NUMBER values come back exactly, beyond double precision, and as text past decimal's range.
            var numbers = await session.Query.ExecuteAsync("SELECT CAST(1234567890123456789.25 AS NUMBER(30,2)), 12345678901234567890123456789012345678, 42 FROM dual");
            Assert.Equal(1234567890123456789.25m, numbers.Rows[0][0]);
            Assert.Equal("12345678901234567890123456789012345678", numbers.Rows[0][1]);
            Assert.Equal(42L, numbers.Rows[0][2]);
            Assert.Equal(2m, Convert.ToDecimal((await session.Query.ExecuteAsync(statements[2].Text)).Rows[0][0], CultureInfo.InvariantCulture));

            // Data editor: paging, filters, and staged changes.
            var customers = new TableRef("CUSTOMERS", server.Username);
            var page = await session.Data.QueryAsync(customers, new DataQuery { PageSize = 2, IncludeTotalCount = true, Filters = [FilterCondition.Contains("EMAIL", "x.io")], Sort = [new SortSpec("ID", Bengine.Enums.SortDirection.Descending)] });
            Assert.Equal(3, page.TotalCount);
            Assert.Equal(2, page.Rows.Count);
            Assert.True(page.HasMore);
            var counts = await session.Writer.ApplyAsync(customers,
            [
                RowChange.Insert(new Dictionary<string, object?> { ["EMAIL"] = "d@x.io", ["BORN"] = "2001-05-06", ["BALANCE"] = "7.25" }),
                RowChange.Update(new Dictionary<string, object?> { ["ID"] = 2 }, new Dictionary<string, object?> { ["BALANCE"] = 99m, ["BORN"] = new DateTime(2000, 1, 2) }),
                RowChange.Delete(new Dictionary<string, object?> { ["ID"] = 3 }),
            ]);
            Assert.Equal([1, 1, 1], counts);
            var preview = Bengine.Introspection.Data.RelationalDataWriter.Preview(DatabaseProvider.Oracle, customers,
                [RowChange.Update(new Dictionary<string, object?> { ["ID"] = 2 }, new Dictionary<string, object?> { ["BORN"] = new DateTime(2000, 1, 2, 10, 30, 0) })]);
            Assert.Contains("TIMESTAMP '2000-01-02 10:30:00'", preview[0], StringComparison.Ordinal);
            Assert.Equal(3, (await session.Data.QueryAsync(customers, new DataQuery { IncludeTotalCount = true })).TotalCount);

            // Explain (plan table) and the catalog behind completion.
            var plan = await Bengine.Introspection.Plans.PlanReader.ExplainAsync(session, "SELECT * FROM orders o JOIN customers c ON c.id = o.customer_id WHERE o.total > 10", analyze: false);
            output.WriteLine(plan.Raw);
            Assert.NotEmpty(plan.Roots);
            var catalog = await session.ReadCatalogAsync();
            Assert.Contains(catalog.Relations, r => r.Name == "CUSTOMERS" && r.Columns.Any(c => c.Name == "ID" && c.IsPrimaryKey));
            Assert.Contains(catalog.ForeignKeys, k => k.Table == "ORDERS" && k.ReferencedTable == "CUSTOMERS");
            var completion = SqlCompletion.Complete("SELECT * FROM customers c JOIN ", "SELECT * FROM customers c JOIN ".Length, catalog);
            Assert.Contains(completion.Items, i => i.Kind == CompletionKind.Join);

            // Find Usages and the object SQL the explorer runs.
            var usages = await ObjectUsages.InDatabaseAsync(session, "ORDERS");
            output.WriteLine(string.Join('\n', usages.Select(u => $"{u.Kind} {u.Name}:{u.Line} {u.Snippet}")));
            Assert.Contains(usages, u => u.Kind == "View" && u.Name.EndsWith("BIG_ORDERS", StringComparison.Ordinal));
            Assert.Contains(usages, u => u.Kind == "Package Body");
            await session.Query.ExecuteAllAsync(ObjectSql.Rename(DatabaseProvider.Oracle, new NodeRef { Kind = NodeKind.Sequence, Schema = server.Username, Name = "SEQ_TICKETS" }, "SEQ_RENAMED"));
            await session.Query.ExecuteAllAsync(ObjectSql.Drop(DatabaseProvider.Oracle, new NodeRef { Kind = NodeKind.Synonym, Schema = server.Username, Name = "CLIENTS" }));
        });
    }

    [Fact]
    public async Task Dumps_compares_and_watches_sessions_when_configured()
    {
        if (Spec is null)
        {
            output.WriteLine("BENGINE_TEST_ORACLE is not set; skipping.");
            return;
        }

        await WithScratchAsync(async source =>
        {
            await WithScratchAsync(async target =>
            {
                await using (var session = await ObjectExplorer.OpenSessionAsync(source, null, null))
                {
                    await ScriptRunner.RunAsync(session, Setup);
                }

                // A Bengine dump of the source replays into the empty target schema.
                var writer = new StringWriter();
                await using (var session = await ObjectExplorer.OpenSessionAsync(source, null, null))
                {
                    var summary = await SqlDump.WriteAsync(session, null, writer, new SqlDumpOptions { RowsPerInsert = 2 });
                    Assert.Equal(6, summary.Rows);
                }

                var dump = writer.ToString().Replace($"\"{source.Username}\".", string.Empty, StringComparison.Ordinal).Replace($"{source.Username}.", string.Empty, StringComparison.Ordinal);
                output.WriteLine(dump);
                await using (var session = await ObjectExplorer.OpenSessionAsync(target, null, null))
                {
                    var run = await ScriptRunner.RunAsync(session, dump);
                    Assert.Equal(0, run.Failed);
                    Assert.Equal("4", Convert.ToString((await session.Query.ExecuteAsync("SELECT MAX(id) + 1 FROM customers")).Rows[0][0], CultureInfo.InvariantCulture));
                    await session.Query.ExecuteAllAsync("INSERT INTO customers (email) VALUES ('new@x.io')");
                    Assert.Equal("4", Convert.ToString((await session.Query.ExecuteAsync("SELECT id FROM customers WHERE email = 'new@x.io'")).Rows[0][0], CultureInfo.InvariantCulture));
                    await session.Query.ExecuteAllAsync("DELETE FROM customers WHERE email = 'new@x.io'");
                    await session.Query.ExecuteAllAsync("UPDATE orders SET total = 999 WHERE id = 2");
                }

                // Data compare across the two schemas finds the edited row and syncs it back.
                await using (var left = await ObjectExplorer.OpenSessionAsync(source, null, null))
                await using (var right = await ObjectExplorer.OpenSessionAsync(target, null, null))
                {
                    var orders = new TableRef("ORDERS", null);
                    var result = await Bengine.Introspection.Compare.DataComparer.CompareAsync(left, orders with { Schema = source.Username }, right, orders with { Schema = target.Username });
                    Assert.Equal(1, result.Different);
                    await Bengine.Introspection.Compare.DataComparer.ApplyAsync(right, orders with { Schema = target.Username }, result, result.SyncChanges());
                    Assert.True((await Bengine.Introspection.Compare.DataComparer.CompareAsync(left, orders with { Schema = source.Username }, right, orders with { Schema = target.Username })).Identical);
                }

                // Server activity, as the administrator.
                var p = Spec!.Split(';');
                var admin = source with { Username = p[3], Password = p[4] };
                await using (var session = await ObjectExplorer.OpenSessionAsync(admin, null, null))
                {
                    var sessions = await Bengine.Introspection.Activity.ServerActivity.SessionsAsync(session);
                    Assert.Contains(sessions, s => s.IsSelf);
                    var locks = await Bengine.Introspection.Activity.ServerActivity.LocksAsync(session);
                    output.WriteLine($"{sessions.Count} session(s), {locks.Count} lock(s)");
                    await session.Query.ExecuteAllAsync("SELECT COUNT(*) FROM all_users");
                    var analyzed = await Bengine.Introspection.Plans.PlanReader.ExplainAsync(session, "SELECT COUNT(*) FROM all_users", analyze: true);
                    Assert.True(analyzed.Analyzed);
                    Assert.Contains(analyzed.Roots, r => r.ActualRows is not null);
                }
            });
        });
    }

    private async Task WithScratchAsync(Func<ServerProfile, Task> test)
    {
        var p = Spec!.Split(';');
        var admin = new ServerProfile
        {
            Name = "oracle-admin", Provider = DatabaseProvider.Oracle, Host = p[0], Port = int.Parse(p[1], CultureInfo.InvariantCulture),
            MaintenanceDatabase = p[2], Username = p[3], Password = p[4], SavePassword = true,
        };
        var user = $"BENGINE_T{Guid.NewGuid():N}"[..20].ToUpperInvariant();
        const string Password = "Scratch_pw1";
        await using (var session = await ObjectExplorer.OpenSessionAsync(admin, null, null))
        {
            foreach (var statement in new[]
            {
                $"CREATE USER {user} IDENTIFIED BY {Password} QUOTA UNLIMITED ON USERS",
                $"GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER, CREATE TYPE, CREATE MATERIALIZED VIEW, CREATE SYNONYM TO {user}",
            })
            {
                await session.Query.ExecuteAllAsync(statement);
            }
        }

        try
        {
            await test(admin with { Name = "oracle", Username = user, Password = Password });
        }
        finally
        {
            Oracle.ManagedDataAccess.Client.OracleConnection.ClearAllPools();
            await using var session = await ObjectExplorer.OpenSessionAsync(admin, null, null);
            await session.Query.ExecuteAllAsync($"DROP USER {user} CASCADE");
        }
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "Bengine.slnx")))
        {
            dir = dir.Parent;
        }

        return dir?.FullName ?? throw new DirectoryNotFoundException("Bengine.slnx not found.");
    }
