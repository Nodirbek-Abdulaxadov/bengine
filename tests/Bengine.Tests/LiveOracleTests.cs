/// <summary>
/// Oracle, live: the schema.json example's generated DDL runs on a real server
/// and introspects back to the same design, and the console, data editor,
/// tree, catalog, and tools work against it. Each test works in a scratch
/// schema (a user) it creates and drops. Runs when <c>BENGINE_TEST_ORACLE</c>
/// holds <c>host;port;service;adminUser;adminPassword</c>.
/// </summary>
