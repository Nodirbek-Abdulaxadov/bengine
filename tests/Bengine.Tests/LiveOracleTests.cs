    private static readonly string? Spec = Environment.GetEnvironmentVariable("BENGINE_TEST_ORACLE");

    [Fact]
    public async Task Runs_the_generated_ddl_and_introspects_it_back_when_configured()
    {
        if (Spec is null)
        {
            output.WriteLine("BENGINE_TEST_ORACLE is not set; skipping.");
            return;
        }

        await WithScratchAsync(async server =>
        {
            var design = SchemaSerializer.FromJson(await File.ReadAllTextAsync(Path.Combine(RepoRoot(), "examples", "shop.schema.json")));
            var ddl = new OracleGenerator().Generate(design);
            output.WriteLine(ddl);
            await using (var session = await ObjectExplorer.OpenSessionAsync(server, null, null))
            {
                var progress = await ScriptRunner.RunAsync(session, ddl);
                Assert.Equal(0, progress.Failed);
            }

            await using (var session = await ObjectExplorer.OpenSessionAsync(server, null, null))
            {
                var live = await session.Introspector.IntrospectAsync();
                output.WriteLine(string.Join(", ", live.Tables.Select(t => $"{t.Name}({t.Columns.Count})")));
                Assert.Equal(design.Tables.Count, live.Tables.Count);

                // Bare design names fold to upper case; compare case-insensitively, ignoring the design's schema.
                var changes = SchemaDiffer.Compare(live, design, new SchemaDiffOptions { IgnoreSchemaNames = true, Provider = DatabaseProvider.Oracle });
                output.WriteLine(string.Join('\n', changes.Select(c => c.Description)));
                Assert.DoesNotContain(changes, c => c is not (CreateViewChange or DropViewChange or CreateSequenceChange or DropSequenceChange));
            }
        });
    }

