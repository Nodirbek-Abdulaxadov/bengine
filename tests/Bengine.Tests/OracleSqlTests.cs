    [Fact]
    public void Generates_oracle_ddl_from_a_design()
    {
        var design = SchemaSerializer.FromJson(File.ReadAllText(Path.Combine(RepoRoot(), "examples", "shop.schema.json")));
        var ddl = new OracleGenerator().Generate(design);

        // Plain names go bare so Oracle folds them to upper case; PostgreSQL's "public" is dropped.
        Assert.Contains("CREATE TABLE categories (", ddl, StringComparison.Ordinal);
        Assert.DoesNotContain("public", ddl, StringComparison.Ordinal);
        Assert.Contains("id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL", ddl, StringComparison.Ordinal);
        Assert.Contains("is_active NUMBER(1) DEFAULT 1 NOT NULL", ddl, StringComparison.Ordinal);
        Assert.Contains("TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL", ddl, StringComparison.Ordinal);
        Assert.Contains("GENERATED ALWAYS AS (quantity * unit_price) VIRTUAL NOT NULL", ddl, StringComparison.Ordinal);
        Assert.Contains("ON DELETE CASCADE", ddl, StringComparison.Ordinal);
        Assert.DoesNotContain("ON UPDATE", ddl, StringComparison.Ordinal);
        Assert.DoesNotContain("ON DELETE NO ACTION", ddl, StringComparison.Ordinal);
        Assert.Contains("NOCYCLE", ddl, StringComparison.Ordinal);
        Assert.DoesNotContain("IF NOT EXISTS", ddl, StringComparison.Ordinal);

        // Live databases keep exact names: only plain upper-case names go bare.
        var exact = new OracleDialect(foldNames: false);
        Assert.Equal("USERS", exact.QuoteIdentifier("USERS"));
        Assert.Equal("\"users\"", exact.QuoteIdentifier("users"));
        Assert.Equal("\"Order Lines\"", new OracleDialect().QuoteIdentifier("Order Lines"));
        Assert.Equal("\"DATE\"", new OracleDialect().QuoteIdentifier("DATE"));
    }

    [Fact]
    public void Renders_oracle_alter_scripts()
    {
        var table = new Table
        {
            Name = "USERS",
            Schema = "APP",
            Columns =
            [
                new Column { Name = "ID", Type = new ColumnTypeOptions { DataType = DbDataType.BigInt } },
                new Column { Name = "EMAIL", Type = new ColumnTypeOptions { DataType = DbDataType.VarChar, Length = 100 }, Nullability = Nullability.Nullable },
            ],
        };
        var changed = new Table
        {
            Name = table.Name,
            Schema = table.Schema,
            Columns =
            [
                table.Columns[0],
                new Column { Name = "EMAIL", Type = new ColumnTypeOptions { DataType = DbDataType.VarChar, Length = 200 }, Default = DefaultValue.Literal("'n/a'"), Comment = "Login" },
                new Column { Name = "AGE", Type = new ColumnTypeOptions { DataType = DbDataType.SmallInt }, Nullability = Nullability.Nullable },
            ],
        };

        var script = AlterScriptGenerator.ForDatabase(DatabaseProvider.Oracle).Render(SchemaDiffer.CompareTables(table, changed, new SchemaDiffOptions { Provider = DatabaseProvider.Oracle }));
        Assert.Equal(
        [
            "ALTER TABLE APP.USERS ADD (AGE NUMBER(5) NULL);",
            "UPDATE APP.USERS SET EMAIL = 'n/a' WHERE EMAIL IS NULL;",
            "ALTER TABLE APP.USERS MODIFY (EMAIL VARCHAR2(200));",
            "ALTER TABLE APP.USERS MODIFY (EMAIL DEFAULT 'n/a');",
            "ALTER TABLE APP.USERS MODIFY (EMAIL NOT NULL);",
            "COMMENT ON COLUMN APP.USERS.EMAIL IS 'Login';",
        ], script.OrderBy(s => s.StartsWith("ALTER TABLE APP.USERS ADD", StringComparison.Ordinal) ? 0 : 1).ToArray());
    }

    [Fact]
    public void Imports_the_ddl_oracle_tools_write()
    {
        Assert.Equal(DatabaseProvider.Oracle, SqlDialectDetector.Detect(MetadataDdl));
        var schema = SqlSchemaParser.ParseAs(MetadataDdl, DatabaseProvider.Oracle);
        Assert.Equal(["EMPLOYEES", "DEPARTMENTS"], schema.Tables.Select(t => t.Name));

        var employees = schema.Tables[0];
        Column Col(string name) => employees.Columns.Single(c => c.Name == name);
        Assert.Equal(IdentityStrategy.Identity, Col("EMPLOYEE_ID").Identity.Strategy);
        Assert.Equal(DbDataType.Integer, Col("EMPLOYEE_ID").Type.DataType);
        Assert.Equal((DbDataType.VarChar, 25, Nullability.NotNull), (Col("EMAIL").Type.DataType, Col("EMAIL").Type.Length, Col("EMAIL").Nullability));
        Assert.Equal((DbDataType.Timestamp, DefaultValueKind.CurrentTimestamp), (Col("HIRE_DATE").Type.DataType, Col("HIRE_DATE").Default.Kind));
        Assert.Equal((DbDataType.Decimal, 8, 2), (Col("SALARY").Type.DataType, Col("SALARY").Type.Precision, Col("SALARY").Type.Scale));
        Assert.Equal(DbDataType.Decimal, Col("BONUS").Type.DataType);
        Assert.Equal(DbDataType.TimestampTz, Col("CREATED").Type.DataType);
        Assert.Equal(DbDataType.Text, Col("NOTES").Type.DataType);
        Assert.Equal(DbDataType.Boolean, Col("ACTIVE").Type.DataType);
        Assert.Equal((GeneratedKind.Virtual, "\"SALARY\"*12"), (Col("TOTAL").Generated!.Kind, Col("TOTAL").Generated!.Expression));
        Assert.Equal("Monthly, in USD", Col("SALARY").Comment);
        Assert.Equal("Staff", employees.Comment);
        Assert.Equal(["EMPLOYEE_ID"], employees.PrimaryKey!.ColumnNames);
        Assert.Contains(employees.Indexes, i => i.Name == "EMP_DEPT_IX");
        Assert.Contains(employees.CheckConstraints, c => c.Name == "EMP_SALARY_MIN");
        var fk = Assert.Single(employees.ForeignKeys);
        Assert.Equal(("DEPARTMENTS", ReferentialAction.SetNull), (fk.ReferencedTable, fk.OnDelete));

        var departments = schema.Tables[1];
        Assert.Equal(DbDataType.VarBinary, departments.Columns.Single(c => c.Name == "CODE").Type.DataType);
        Assert.Equal(DefaultValueKind.Expression, departments.Columns.Single(c => c.Name == "SEQ_ID").Default.Kind);
        Assert.Contains("NEXTVAL", departments.Columns.Single(c => c.Name == "SEQ_ID").Default.Value, StringComparison.Ordinal);
    }

    [Fact]
    public void Splits_oracle_scripts_the_sqlplus_way()
    {
        const string Script = """
            SELECT q'[a;b]' FROM dual;
            DECLARE
              n NUMBER;
            BEGIN
              n := 1;
              IF n > 0 THEN
                NULL;
              END IF;
            END;
            /
            CREATE OR REPLACE PACKAGE BODY api AS
              PROCEDURE p IS BEGIN NULL; END;
            END api;
            /
            BEGIN dbms_output.put_line('x'); END;
            UPDATE t SET a = 1;
            """;
        var statements = SqlScript.Split(Script, DatabaseProvider.Oracle).Select(s => s.Text).ToList();
        Assert.Equal(5, statements.Count);
        Assert.Equal("SELECT q'[a;b]' FROM dual", statements[0]);
        Assert.StartsWith("DECLARE", statements[1], StringComparison.Ordinal);
        Assert.EndsWith("END", statements[1], StringComparison.Ordinal);
        Assert.StartsWith("CREATE OR REPLACE PACKAGE BODY", statements[2], StringComparison.Ordinal);
        Assert.Equal("BEGIN dbms_output.put_line('x'); END", statements[3]);

        // What the driver receives: SQL loses the semicolon, PL/SQL keeps (or gains) it.
        Assert.Equal("SELECT 1 FROM dual", SqlScript.ForOracle("SELECT 1 FROM dual;"));
        Assert.Equal("BEGIN dbms_output.put_line('x'); END;", SqlScript.ForOracle(statements[3]));
        Assert.EndsWith("END api;", SqlScript.ForOracle(statements[2] + "\n/"), StringComparison.Ordinal);
    }

    [Fact]
    public void Writes_oracle_literals_and_names()
    {
        Assert.Equal("TIMESTAMP '2026-10-14 13:45:07.5'", SqlLiterals.Format(new DateTime(2026, 10, 14, 13, 45, 7, 500), DatabaseProvider.Oracle));
        Assert.Equal("DATE '2026-10-14'", SqlLiterals.Format(new DateTime(2026, 10, 14), DatabaseProvider.Oracle));
        Assert.Equal("1", SqlLiterals.Format(true, DatabaseProvider.Oracle));
        Assert.Equal("HEXTORAW('00FF')", SqlLiterals.Format(new byte[] { 0, 255 }, DatabaseProvider.Oracle));
        Assert.Equal("INTERVAL '1 02:03:04' DAY TO SECOND", SqlLiterals.Format(new TimeSpan(1, 2, 3, 4), DatabaseProvider.Oracle));
        Assert.Equal("'it''s'", SqlLiterals.Format("it's", DatabaseProvider.Oracle));
        Assert.Equal("USERS", SqlKeywords.QuoteIfNeeded("USERS", DatabaseProvider.Oracle));
        Assert.Equal("\"users\"", SqlKeywords.QuoteIfNeeded("users", DatabaseProvider.Oracle));
        Assert.Equal("\"LEVEL\"", SqlKeywords.QuoteIfNeeded("LEVEL", DatabaseProvider.Oracle));
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "Bengine.slnx")))
        {
            dir = dir.Parent;
        }

        return dir?.FullName ?? throw new DirectoryNotFoundException("Bengine.slnx not found.");
    }
