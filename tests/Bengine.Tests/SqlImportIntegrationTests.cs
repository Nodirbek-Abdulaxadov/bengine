namespace Bengine.Tests;

using System.Linq;
using Bengine.Enums;
using Bengine.Generators;
using Bengine.Generators.Sql;
using Bengine.Models;
using Bengine.Parsing;
using Bengine.Serialization;

public class SqlImportIntegrationTests
{
    private const string PostgresSql = """
        CREATE TABLE public.users (
            id BIGSERIAL PRIMARY KEY,
            email VARCHAR(320) NOT NULL,
            is_active BOOLEAN NOT NULL DEFAULT true,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE UNIQUE INDEX ux_users_email ON public.users (email);
        CREATE TABLE public.orders (
            id BIGSERIAL PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
            total NUMERIC(12,2) NOT NULL DEFAULT 0,
            CONSTRAINT ck_orders_total CHECK (total >= 0)
        );
        """;

    private const string MySql = """
        CREATE TABLE `products` (
          `id` BIGINT NOT NULL AUTO_INCREMENT,
          `sku` VARCHAR(64) NOT NULL,
          `price` DECIMAL(12,2) NOT NULL,
          `active` TINYINT(1) NOT NULL DEFAULT 1,
          PRIMARY KEY (`id`),
          UNIQUE KEY `ux_products_sku` (`sku`)
        ) ENGINE=InnoDB;
        """;

    private const string SqlServerSql = """
        CREATE TABLE [dbo].[customers] (
            [id] BIGINT IDENTITY(1,1) NOT NULL,
            [email] NVARCHAR(320) NOT NULL,
            [notes] VARCHAR(MAX) NULL,
            CONSTRAINT [pk_customers] PRIMARY KEY ([id])
        );
        """;

    private const string SqliteSql = """
        CREATE TABLE notes (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            body TEXT
        );
        """;

    public static IEnumerable<object[]> Dialects()
    {
        yield return [DatabaseProvider.PostgreSql, PostgresSql];
        yield return [DatabaseProvider.MySql, MySql];
        yield return [DatabaseProvider.SqlServer, SqlServerSql];
        yield return [DatabaseProvider.Sqlite, SqliteSql];
    }

    [Theory]
    [MemberData(nameof(Dialects))]
    public void Detected_dialect_matches_the_provider(DatabaseProvider provider, string sql)
    {
        var result = SqlSchemaParser.Import(sql);

        Assert.Equal(provider, result.Provider);
    }

    [Theory]
    [MemberData(nameof(Dialects))]
    public void Import_then_generate_then_reimport_is_structurally_stable(DatabaseProvider provider, string sql)
    {
        var generator = GeneratorFor(provider);

        var first = SqlSchemaParser.ParseAs(sql, provider);
        var generated = generator.Generate(first);
        var second = SqlSchemaParser.ParseAs(generated, provider);

        AssertSameShape(first, second);
    }

    [Theory]
    [MemberData(nameof(Dialects))]
    public void Imported_schema_survives_json_round_trip(DatabaseProvider provider, string sql)
    {
        var generator = GeneratorFor(provider);
        var schema = SqlSchemaParser.ParseAs(sql, provider);

        var restored = SchemaSerializer.FromJson(SchemaSerializer.ToJson(schema));

        Assert.Equal(generator.Generate(schema), generator.Generate(restored));
    }

    [Fact]
    public void Cross_dialect_import_preserves_structure()
    {
        // MySQL source imported, then rendered as PostgreSQL: logical types and
        // constraints must survive the dialect crossing.
        var schema = SqlSchemaParser.ParseAs(MySql, DatabaseProvider.MySql);
        var table = schema.Tables.Single();

        var active = table.Columns.Single(c => c.Name == "active");
        Assert.Equal(DbDataType.Boolean, active.Type.DataType); // tinyint(1) -> boolean

        var postgres = new PostgreSqlGenerator().Generate(schema);
        Assert.Contains("\"active\" boolean", postgres);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", postgres); // auto_increment -> identity
    }

    private static ISqlGenerator GeneratorFor(DatabaseProvider provider) => provider switch
    {
        DatabaseProvider.PostgreSql => new PostgreSqlGenerator(),
        DatabaseProvider.SqlServer => new SqlServerGenerator(),
        DatabaseProvider.MySql => new MySqlGenerator(),
        DatabaseProvider.Sqlite => new SqliteGenerator(),
        _ => throw new ArgumentOutOfRangeException(nameof(provider)),
    };

    private static void AssertSameShape(DatabaseSchema a, DatabaseSchema b)
    {
        Assert.Equal(a.Tables.Count, b.Tables.Count);
        foreach (var (ta, tb) in a.Tables.Zip(b.Tables))
        {
            Assert.Equal(ta.Name, tb.Name);
            Assert.Equal(
                ta.Columns.Select(c => (c.Name, c.Type.DataType, c.Nullability)),
                tb.Columns.Select(c => (c.Name, c.Type.DataType, c.Nullability)));
            Assert.Equal(ta.PrimaryKey?.ColumnNames, tb.PrimaryKey?.ColumnNames);
            Assert.Equal(ta.ForeignKeys.Count, tb.ForeignKeys.Count);
            Assert.Equal(ta.Indexes.Count, tb.Indexes.Count);
            Assert.Equal(ta.CheckConstraints.Count, tb.CheckConstraints.Count);
        }
    }
}
