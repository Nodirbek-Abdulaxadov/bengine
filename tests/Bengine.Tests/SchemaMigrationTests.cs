    [Fact]
    public void Renders_dialect_specific_alter_statements()
    {
        var before = new Table
        {
            Name = "t",
            Schema = "s",
            Columns = [new Column { Name = "a", Type = ColumnTypeOptions.Of(DbDataType.Integer) }, new Column { Name = "b", Type = new ColumnTypeOptions { DataType = DbDataType.VarChar, Length = 10 }, Nullability = Nullability.Nullable }],
        };
        var after = SchemaDiffer.Copy(before, columns:
        [
            before.Columns[0],
            new Column { Name = "b", Type = new ColumnTypeOptions { DataType = DbDataType.VarChar, Length = 20 }, Default = DefaultValue.Literal("'x'") },
        ]);
        var changes = SchemaDiffer.CompareTables(before, after);

        var change = Assert.IsType<AlterColumnChange>(Assert.Single(changes));
        Assert.Equal(ColumnChange.Type | ColumnChange.Nullability | ColumnChange.Default, change.Changes);
        Assert.Equal(
            [
                "UPDATE \"s\".\"t\" SET \"b\" = 'x' WHERE \"b\" IS NULL;",
                "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"b\" TYPE varchar(20) USING \"b\"::varchar(20);",
                "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"b\" SET NOT NULL;",
                "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"b\" SET DEFAULT 'x';",
            ],
            AlterScriptGenerator.For(DatabaseProvider.PostgreSql).Render(changes).ToArray());
        Assert.Equal(
            ["UPDATE `t` SET `b` = 'x' WHERE `b` IS NULL;", "ALTER TABLE `t` MODIFY COLUMN `b` varchar(20) NOT NULL DEFAULT 'x';"],
            AlterScriptGenerator.For(DatabaseProvider.MySql).Render(changes).ToArray());
        var mssql = AlterScriptGenerator.For(DatabaseProvider.SqlServer).Render(changes);
        Assert.Equal("ALTER TABLE [s].[t] ALTER COLUMN [b] varchar(20) NOT NULL;", mssql[1]);
        Assert.StartsWith("DECLARE @n sysname;", mssql[2], StringComparison.Ordinal);
        Assert.Equal("ALTER TABLE [s].[t] ADD CONSTRAINT [DF_t_b] DEFAULT 'x' FOR [b];", mssql[3]);
    }

    private async Task RoundTripAsync(DatabaseProvider provider, string fromConnection, string toConnection, string fromDdl, string toDdl)
    {
        await ExecuteScriptAsync(provider, fromConnection, fromDdl);
        await ExecuteScriptAsync(provider, toConnection, toDdl);

        var source = await IntrospectAsync(provider, fromConnection);
        var target = await IntrospectAsync(provider, toConnection);
        var options = new SchemaDiffOptions { IgnoreSchemaNames = true, Provider = provider };
        var changes = SchemaDiffer.Compare(source, target, options);
        Assert.NotEmpty(changes);
        var script = AlterScriptGenerator.For(provider).Render(changes, source, target);
        output.WriteLine($"-- {provider}\n" + string.Join("\n", script));

        await using (var session = await DatabaseSession.OpenAsync(provider, fromConnection))
        {
            foreach (var statement in script)
            {
                try
                {
                    await session.Query.ExecuteAllAsync(statement);
                }
                catch (IntrospectionException ex)
                {
                    throw new Xunit.Sdk.XunitException($"{provider}: {ex.Message}\n{statement}");
                }
            }
        }

        var migrated = await IntrospectAsync(provider, fromConnection);
        var remaining = SchemaDiffer.Compare(migrated, target, options);
        Assert.True(remaining.Count == 0, $"{provider} still differs:\n" + string.Join("\n", remaining.Select(r => r.Description)));
    }

    private static async Task<DatabaseSchema> IntrospectAsync(DatabaseProvider provider, string connection)
    {
        await using var session = await DatabaseSession.OpenAsync(provider, connection);
        var schema = provider switch
        {
            DatabaseProvider.PostgreSql => "public",
            DatabaseProvider.SqlServer => "dbo",
            DatabaseProvider.MySql => session.Database,
            _ => null,
        };
        return await session.Introspector.IntrospectAsync(schema);
    }

    private static async Task ExecuteScriptAsync(DatabaseProvider provider, string connection, string script)
    {
        await using var session = await DatabaseSession.OpenAsync(provider, connection);
        foreach (var statement in Introspection.Sql.SqlScript.Split(script, provider))
        {
            await session.Query.ExecuteAllAsync(statement.Text);
        }
    }

    private static async Task WithScratchDatabasesAsync(DatabaseProvider provider, string spec, Func<string, string, Task> body)
    {
        var p = spec.Split(';');
        var suffix = Guid.NewGuid().ToString("N")[..10];
        var names = new[] { $"bengine_mig_a_{suffix}", $"bengine_mig_b_{suffix}" };
        string Connection(string database) => provider switch
        {
            DatabaseProvider.PostgreSql => new Npgsql.NpgsqlConnectionStringBuilder { Host = p[0], Port = int.Parse(p[1], System.Globalization.CultureInfo.InvariantCulture), Database = database, Username = p[3], Password = p[4] }.ConnectionString,
            DatabaseProvider.MySql => new MySqlConnector.MySqlConnectionStringBuilder { Server = p[0], Port = uint.Parse(p[1], System.Globalization.CultureInfo.InvariantCulture), Database = database, UserID = p[3], Password = p[4] }.ConnectionString,
            _ => new Microsoft.Data.SqlClient.SqlConnectionStringBuilder { DataSource = $"{p[0]},{p[1]}", InitialCatalog = database, UserID = p[3], Password = p[4], TrustServerCertificate = true }.ConnectionString,
        };

        var admin = Connection(p[2]);
        foreach (var name in names)
        {
            await ExecuteScriptAsync(provider, admin, $"CREATE DATABASE {name}");
        }

        try
        {
            await body(Connection(names[0]), Connection(names[1]));
        }
        finally
        {
            Npgsql.NpgsqlConnection.ClearAllPools();
            MySqlConnector.MySqlConnection.ClearAllPools();
            Microsoft.Data.SqlClient.SqlConnection.ClearAllPools();
            foreach (var name in names)
            {
                var drop = provider switch
                {
                    DatabaseProvider.PostgreSql => $"DROP DATABASE IF EXISTS {name} WITH (FORCE)",
                    DatabaseProvider.SqlServer => $"ALTER DATABASE {name} SET SINGLE_USER WITH ROLLBACK IMMEDIATE;\nDROP DATABASE {name}",
                    _ => $"DROP DATABASE IF EXISTS {name}",
                };
                await ExecuteScriptAsync(provider, admin, drop);
            }
        }
    }
}

/// <summary>Tests of the table designer behind "Modify Table" and "New Table".</summary>
[Collection("live-postgres")]
public sealed class TableDesignTests(ITestOutputHelper output)
{
    [Fact]
    public async Task Modifies_a_sqlite_table_with_renames_type_changes_keys_and_keeps_rows()
    {
        var path = Path.Combine(Path.GetTempPath(), $"bengine_design_{Guid.NewGuid():N}.db");
        try
        {
            await using var session = await DatabaseSession.OpenAsync(DatabaseProvider.Sqlite, $"Data Source={path}");
            await session.Query.ExecuteAllAsync("CREATE TABLE users (id INTEGER PRIMARY KEY, mail VARCHAR(50) NOT NULL, age INTEGER)");
            await session.Query.ExecuteAllAsync("CREATE TABLE posts (id INTEGER PRIMARY KEY, author INTEGER, title TEXT)");
            await session.Query.ExecuteAllAsync("CREATE TRIGGER trg_posts AFTER INSERT ON posts BEGIN SELECT 1; END");
            await session.Query.ExecuteAllAsync("INSERT INTO users (mail, age) VALUES ('a@x.io', 30); INSERT INTO posts (author, title) VALUES (1, 'hi')");

            var unchanged = Introspection.Design.TableDesign.From(await session.Introspector.IntrospectTableAsync(new Introspection.Model.TableRef("users")), DatabaseProvider.Sqlite);
            Assert.Empty(unchanged.Changes());

            var design = Introspection.Design.TableDesign.From(await session.Introspector.IntrospectTableAsync(new Introspection.Model.TableRef("posts")), DatabaseProvider.Sqlite);
            design.Columns.Single(c => c.Name == "author").Name = "user_id";
            design.Columns.Single(c => c.Name == "title").Nullable = false;
            design.Columns.Single(c => c.Name == "title").Default = "'untitled'";
            design.Columns.Add(new Introspection.Design.ColumnDesign { Name = "views", Type = "INTEGER", Default = "0" });
            design.ForeignKeys.Add(new Introspection.Design.ForeignKeyDesign { Name = "fk_posts_user", Columns = "user_id", ReferencedTable = "users", ReferencedColumns = "id" });
            design.Indexes.Add(new Introspection.Design.IndexDesign { Name = "ix_posts_user", Columns = "user_id" });
            Assert.Empty(design.Validate());

            var generator = Bengine.Generators.Migrations.AlterScriptGenerator.For(DatabaseProvider.Sqlite);
            var script = design.Script();
            output.WriteLine(string.Join("\n", script));
            Assert.Contains(script, s => s.StartsWith("CREATE TABLE \"posts__bengine_new\"", StringComparison.Ordinal));
            Assert.Contains(script, s => s.Contains("SELECT \"id\", \"author\", COALESCE(\"title\", 'untitled')", StringComparison.Ordinal));

            // Triggers dropped with the old table are replayed.
            var triggers = (await session.Query.ExecuteAsync("SELECT sql FROM sqlite_master WHERE type = 'trigger' AND tbl_name = 'posts'")).Rows.Select(r => (string)r[0]!).ToList();
            generator.RebuildEpilogue = _ => triggers;
            foreach (var statement in generator.Render(design.Changes(), new DatabaseSchema { Name = "s", Tables = [design.Original!] }, new DatabaseSchema { Name = "t", Tables = [design.ToTable()] }))
            {
                await session.Query.ExecuteAllAsync(statement);
            }

            var after = Introspection.Design.TableDesign.From(await session.Introspector.IntrospectTableAsync(new Introspection.Model.TableRef("posts")), DatabaseProvider.Sqlite);
            Assert.Equal(["id", "user_id", "title", "views"], after.Columns.Select(c => c.Name).ToArray());
            Assert.Equal("users", Assert.Single(after.ForeignKeys).ReferencedTable);
            Assert.Equal("hi", (await session.Query.ExecuteAsync("SELECT title FROM posts WHERE user_id = 1")).Rows[0][0]);
            Assert.Single((await session.Query.ExecuteAsync("SELECT 1 FROM sqlite_master WHERE type = 'trigger' AND name = 'trg_posts'")).Rows);
        }
        finally
        {
            Microsoft.Data.Sqlite.SqliteConnection.ClearAllPools();
            File.Delete(path);
        }
    }

    [Fact]
    public async Task Designs_a_new_table_and_renames_on_postgres_when_configured()
    {
        if (Environment.GetEnvironmentVariable("BENGINE_TEST_PG") is not { Length: > 0 } spec)
        {
            return;
        }

        var p = spec.Split(';');
        var admin = new Npgsql.NpgsqlConnectionStringBuilder { Host = p[0], Port = int.Parse(p[1], System.Globalization.CultureInfo.InvariantCulture), Database = p[2], Username = p[3], Password = p[4] }.ConnectionString;
        var name = $"bengine_design_{Guid.NewGuid():N}"[..26];
        await using (var a = await DatabaseSession.OpenAsync(DatabaseProvider.PostgreSql, admin))
        {
            await a.Query.ExecuteAllAsync($"CREATE DATABASE {name}");
        }

        try
        {
            await using var session = await DatabaseSession.OpenAsync(DatabaseProvider.PostgreSql, new Npgsql.NpgsqlConnectionStringBuilder(admin) { Database = name }.ConnectionString);
            var design = new Introspection.Design.TableDesign(DatabaseProvider.PostgreSql, "public") { Name = "accounts", Comment = "money" };
            design.Columns.Add(new Introspection.Design.ColumnDesign { Name = "id", Type = "bigint", PrimaryKey = true, Identity = true, Nullable = false });
            design.Columns.Add(new Introspection.Design.ColumnDesign { Name = "owner", Type = "text", Nullable = false, Comment = "who" });
            design.Columns.Add(new Introspection.Design.ColumnDesign { Name = "balance", Type = "numeric(12,2)", Default = "0" });
            design.Checks.Add(new Introspection.Design.CheckDesign { Name = "ck_balance", Expression = "balance >= 0" });
            foreach (var statement in design.Script())
            {
                await session.Query.ExecuteAllAsync(statement);
            }

            var loaded = Introspection.Design.TableDesign.From(await session.Introspector.IntrospectTableAsync(new Introspection.Model.TableRef("accounts", "public")), DatabaseProvider.PostgreSql);
            Assert.Empty(loaded.Changes());
            Assert.Equal("money", loaded.Comment);
            Assert.Equal("who", loaded.Columns[1].Comment);

            loaded.Name = "wallets";
            loaded.Columns[1].Name = "holder";
            loaded.Columns[2].Type = "numeric(14,2)";
            loaded.Indexes.Add(new Introspection.Design.IndexDesign { Name = "ix_wallets_holder", Columns = "holder", Unique = true });
            var script = loaded.Script();
            output.WriteLine(string.Join("\n", script));
            foreach (var statement in script)
            {
                await session.Query.ExecuteAllAsync(statement);
            }

            var renamed = await session.Introspector.IntrospectTableAsync(new Introspection.Model.TableRef("wallets", "public"));
            Assert.Equal(["id", "holder", "balance"], renamed.Columns.Select(c => c.Name).ToArray());
            Assert.Equal("ix_wallets_holder", Assert.Single(renamed.Indexes).Name);
        }
        finally
        {
            Npgsql.NpgsqlConnection.ClearAllPools();
            await using var a = await DatabaseSession.OpenAsync(DatabaseProvider.PostgreSql, admin);
            await a.Query.ExecuteAllAsync($"DROP DATABASE IF EXISTS {name} WITH (FORCE)");
        }
    }
