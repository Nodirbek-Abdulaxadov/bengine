/// <summary>
/// Round-trip tests of schema comparison and <c>ALTER</c> generation against
/// real databases: two schemas are created from DDL, introspected, compared,
/// the generated script is applied to the first, and the comparison is
/// repeated — it must come back empty. SQLite always runs; PostgreSQL, MySQL,
/// MariaDB, and SQL Server run when <c>BENGINE_TEST_PG</c>,
/// <c>BENGINE_TEST_MYSQL</c>, <c>BENGINE_TEST_MARIADB</c>, or
/// <c>BENGINE_TEST_MSSQL</c> (<c>host;port;database;user;password</c>) are set,
/// each in scratch databases that are dropped afterwards.
/// </summary>
[Collection("live-postgres")]
public sealed class SchemaMigrationTests(ITestOutputHelper output)
{
    private const string SqliteFrom = """
        CREATE TABLE users (id INTEGER PRIMARY KEY, email VARCHAR(50) NOT NULL, nickname TEXT, legacy TEXT);
        CREATE INDEX ix_users_nick ON users(nickname);
        CREATE TABLE orders (id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL, total REAL);
        CREATE TABLE gone (id INTEGER PRIMARY KEY);
        INSERT INTO users (email, nickname, legacy) VALUES ('a@x.io', 'al', 'x'), ('b@x.io', NULL, 'y');
        INSERT INTO orders (user_id, total) VALUES (1, 10), (2, 20);
        """;

    private const string SqliteTo = """
        CREATE TABLE users (id INTEGER PRIMARY KEY, email VARCHAR(100) NOT NULL, nickname TEXT NOT NULL DEFAULT 'anon', score INTEGER DEFAULT 0);
        CREATE UNIQUE INDEX ux_users_email ON users(email);
        CREATE TABLE orders (id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), total REAL, CONSTRAINT ck_total CHECK (total >= 0));
        CREATE TABLE audit (id INTEGER PRIMARY KEY, note TEXT NOT NULL);
        """;

    [Fact]
    public async Task Migrates_a_sqlite_schema_and_keeps_its_rows()
    {
        var from = Path.Combine(Path.GetTempPath(), $"bengine_mig_from_{Guid.NewGuid():N}.db");
        var to = Path.Combine(Path.GetTempPath(), $"bengine_mig_to_{Guid.NewGuid():N}.db");
        try
        {
            await RoundTripAsync(DatabaseProvider.Sqlite, $"Data Source={from}", $"Data Source={to}", SqliteFrom, SqliteTo);

            await using var session = await DatabaseSession.OpenAsync(DatabaseProvider.Sqlite, $"Data Source={from}");
            var rows = await session.Query.ExecuteAsync("SELECT email, nickname, score FROM users ORDER BY id");
            Assert.Equal(2, rows.Rows.Count);
            Assert.Equal("a@x.io", rows.Rows[0][0]);
            Assert.Equal(2, (await session.Query.ExecuteAsync("SELECT count(*) FROM orders")).Rows[0][0] is long n ? (int)n : -1);
        }
        finally
        {
            Microsoft.Data.Sqlite.SqliteConnection.ClearAllPools();
            File.Delete(from);
            File.Delete(to);
        }
    }

    [Fact]
    public async Task Migrates_a_live_postgres_schema_when_configured()
    {
        if (Environment.GetEnvironmentVariable("BENGINE_TEST_PG") is not { Length: > 0 } spec)
        {
            output.WriteLine("BENGINE_TEST_PG is not set; skipping.");
            return;
        }

        await WithScratchDatabasesAsync(DatabaseProvider.PostgreSql, spec, (from, to) => RoundTripAsync(DatabaseProvider.PostgreSql, from, to, """
            CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email varchar(50) NOT NULL, nickname text, legacy text, tags text[]);
            CREATE INDEX ix_users_nick ON users(nickname);
            CREATE TABLE orders (id bigserial PRIMARY KEY, user_id bigint NOT NULL, total numeric(10,2));
            CREATE TABLE gone (id int PRIMARY KEY);
            COMMENT ON TABLE users IS 'people';
            INSERT INTO users (email, nickname, legacy) VALUES ('a@x.io', 'al', 'x'), ('b@x.io', 'bo', 'y');
            """, """
            CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email varchar(100) NOT NULL, nickname text NOT NULL DEFAULT 'anon', tags text[], score integer DEFAULT 0, external_id uuid);
            CREATE UNIQUE INDEX ux_users_email ON users(email);
            CREATE TABLE orders (id bigserial PRIMARY KEY, user_id bigint NOT NULL, total numeric(12,2), CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE, CONSTRAINT ck_total CHECK (total >= 0));
            CREATE TABLE audit (id serial PRIMARY KEY, note text NOT NULL, at timestamptz DEFAULT now());
            COMMENT ON TABLE users IS 'customers';
            """));
    }

    [Fact]
    public async Task Migrates_live_mysql_and_mariadb_schemas_when_configured()
    {
        const string from = """
            CREATE TABLE users (id int AUTO_INCREMENT PRIMARY KEY, email varchar(50) NOT NULL, nickname text, legacy text);
            CREATE INDEX ix_users_nick ON users(nickname(20));
            CREATE TABLE orders (id int AUTO_INCREMENT PRIMARY KEY, user_id int NOT NULL, total decimal(10,2));
            CREATE TABLE gone (id int PRIMARY KEY);
            INSERT INTO users (email, nickname, legacy) VALUES ('a@x.io', 'al', 'x');
            """;
        const string to = """
            CREATE TABLE users (id int AUTO_INCREMENT PRIMARY KEY, email varchar(100) NOT NULL, nickname varchar(40) NOT NULL DEFAULT 'anon', score int DEFAULT 0);
            CREATE UNIQUE INDEX ux_users_email ON users(email);
            CREATE TABLE orders (id int AUTO_INCREMENT PRIMARY KEY, user_id int NOT NULL, total decimal(12,2), CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id));
            CREATE TABLE audit (id int AUTO_INCREMENT PRIMARY KEY, note text NOT NULL);
            """;

        var ran = false;
        foreach (var variable in new[] { "BENGINE_TEST_MYSQL", "BENGINE_TEST_MARIADB" })
        {
            if (Environment.GetEnvironmentVariable(variable) is { Length: > 0 } spec)
            {
                ran = true;
                await WithScratchDatabasesAsync(DatabaseProvider.MySql, spec, (a, b) => RoundTripAsync(DatabaseProvider.MySql, a, b, from, to));
            }
        }

        if (!ran)
        {
            output.WriteLine("BENGINE_TEST_MYSQL / BENGINE_TEST_MARIADB are not set; skipping.");
        }
    }

    [Fact]
    public async Task Migrates_a_live_sql_server_schema_when_configured()
    {
        if (Environment.GetEnvironmentVariable("BENGINE_TEST_MSSQL") is not { Length: > 0 } spec)
        {
            output.WriteLine("BENGINE_TEST_MSSQL is not set; skipping.");
            return;
        }

        await WithScratchDatabasesAsync(DatabaseProvider.SqlServer, spec, (from, to) => RoundTripAsync(DatabaseProvider.SqlServer, from, to, """
            CREATE TABLE users (id int IDENTITY(1,1) PRIMARY KEY, email nvarchar(50) NOT NULL, nickname nvarchar(40) NULL, legacy nvarchar(max));
            CREATE INDEX ix_users_nick ON users(nickname);
