            CREATE TABLE gone (id int PRIMARY KEY);
            INSERT INTO users (email, nickname, legacy) VALUES (N'a@x.io', N'al', N'x');
            """, """
            CREATE TABLE users (id int IDENTITY(1,1) PRIMARY KEY, email nvarchar(100) NOT NULL, nickname nvarchar(40) NOT NULL DEFAULT N'anon', score int DEFAULT 0);
            CREATE UNIQUE INDEX ux_users_email ON users(email);
            CREATE TABLE orders (id int IDENTITY(1,1) PRIMARY KEY, user_id int NOT NULL, total decimal(12,2), CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id), CONSTRAINT ck_total CHECK (total >= 0));
            CREATE TABLE audit (id int IDENTITY(1,1) PRIMARY KEY, note nvarchar(max) NOT NULL);
