namespace Bengine.Generators.Sql;

using Bengine.Enums;
using Bengine.Models.Options;

/// <summary>PostgreSQL syntax tokens for <see cref="SqlGeneratorBase"/>.</summary>
public sealed class PostgreSqlDialect : SqlDialect
{
    /// <inheritdoc />
    public override DatabaseProvider Provider => DatabaseProvider.PostgreSql;

    /// <inheritdoc />
    public override SqlDialectFeature Features =>
        SqlDialectFeature.IfNotExists
        | SqlDialectFeature.Schemas
        | SqlDialectFeature.Sequences
        | SqlDialectFeature.CheckConstraints
        | SqlDialectFeature.PartialIndexes
        | SqlDialectFeature.DeferrableConstraints
        | SqlDialectFeature.GeneratedColumns;

    /// <inheritdoc />
    public override string QuoteIdentifier(string identifier) => $"\"{identifier}\"";

    /// <inheritdoc />
    public override string RenderIdentity(IdentityOptions identity) => identity.Strategy switch
    {
        IdentityStrategy.Identity or IdentityStrategy.AutoIncrement => " GENERATED BY DEFAULT AS IDENTITY",
        _ => string.Empty,
    };
}
