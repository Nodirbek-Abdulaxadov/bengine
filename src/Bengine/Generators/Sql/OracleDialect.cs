namespace Bengine.Generators.Sql;

using System.Text.RegularExpressions;
using Bengine.Enums;
using Bengine.Models.Options;

/// <summary>
/// Oracle Database (12c and later): identity columns, virtual columns, and
/// sequences; <c>DEFAULT</c> and identity before <c>NOT NULL</c>; foreign keys
/// with only <c>ON DELETE CASCADE</c>/<c>SET NULL</c> and no <c>ON UPDATE</c>.
/// <para>
/// Names come in two modes. Designs (<c>foldNames</c>, the default) write plain
/// names bare, so Oracle folds <c>users</c> to <c>USERS</c> as Oracle DDL
/// usually does, and bare names in checks and views resolve; PostgreSQL's
/// <c>public</c> schema is dropped. Live databases (<c>foldNames: false</c>)
/// write a name bare only when it is plain upper case and quote it otherwise,
/// so objects created with quoted mixed-case names are reached exactly.
/// </para>
/// </summary>
public sealed partial class OracleDialect : SqlDialect
{
    private readonly bool _foldNames;

    /// <summary>Creates the dialect.</summary>
    /// <param name="foldNames">Whether plain names are written bare (designs) or kept exactly (live databases).</param>
    public OracleDialect(bool foldNames = true) => _foldNames = foldNames;

    // Reserved words that cannot be bare identifiers.
    private static readonly HashSet<string> Reserved = new(StringComparer.OrdinalIgnoreCase)
    {
        "ACCESS", "ADD", "ALL", "ALTER", "AND", "ANY", "AS", "ASC", "AUDIT", "BETWEEN", "BY", "CHAR", "CHECK", "CLUSTER",
        "COLUMN", "COMMENT", "COMPRESS", "CONNECT", "CREATE", "CURRENT", "DATE", "DECIMAL", "DEFAULT", "DELETE", "DESC",
        "DISTINCT", "DROP", "ELSE", "EXCLUSIVE", "EXISTS", "FILE", "FLOAT", "FOR", "FROM", "GRANT", "GROUP", "HAVING",
        "IDENTIFIED", "IMMEDIATE", "IN", "INCREMENT", "INDEX", "INITIAL", "INSERT", "INTEGER", "INTERSECT", "INTO", "IS",
        "LEVEL", "LIKE", "LOCK", "LONG", "MAXEXTENTS", "MINUS", "MLSLABEL", "MODE", "MODIFY", "NOAUDIT", "NOCOMPRESS",
        "NOT", "NOWAIT", "NULL", "NUMBER", "OF", "OFFLINE", "ON", "ONLINE", "OPTION", "OR", "ORDER", "PCTFREE", "PRIOR",
        "PUBLIC", "RAW", "RENAME", "RESOURCE", "REVOKE", "ROW", "ROWID", "ROWNUM", "ROWS", "SELECT", "SESSION", "SET",
        "SHARE", "SIZE", "SMALLINT", "START", "SUCCESSFUL", "SYNONYM", "SYSDATE", "TABLE", "THEN", "TO", "TRIGGER", "UID",
        "UNION", "UNIQUE", "UPDATE", "USER", "VALIDATE", "VALUES", "VARCHAR", "VARCHAR2", "VIEW", "WHENEVER", "WHERE", "WITH",
    };

    /// <inheritdoc />
    public override DatabaseProvider Provider => DatabaseProvider.Oracle;

    /// <inheritdoc />
    public override SqlDialectFeature Features =>
        SqlDialectFeature.Schemas
        | SqlDialectFeature.Sequences
        | SqlDialectFeature.CheckConstraints
        | SqlDialectFeature.DeferrableConstraints
        | SqlDialectFeature.GeneratedColumns;

    /// <inheritdoc />
    public override bool DefaultBeforeNullability => true;

    /// <inheritdoc />
    public override string NoCycleKeyword => "NOCYCLE";

    /// <inheritdoc />
    public override bool NullabilityOnGeneratedColumns => true;

    /// <inheritdoc />
    public override string QuoteIdentifier(string identifier) =>
        (_foldNames ? FoldableName() : PlainName()).IsMatch(identifier) && !Reserved.Contains(identifier)
            ? identifier
            : $"\"{identifier.Replace("\"", "\"\"", StringComparison.Ordinal)}\"";

    /// <inheritdoc />
    public override string? EffectiveSchema(string? schema) =>
        schema is null || schema.Equals("public", StringComparison.OrdinalIgnoreCase) ? null : schema;

    /// <inheritdoc />
    public override string RenderIdentity(IdentityOptions identity) => identity.Strategy switch
    {
        IdentityStrategy.Identity or IdentityStrategy.AutoIncrement =>
            identity.StartValue == 1 && identity.Increment == 1
                ? " GENERATED BY DEFAULT AS IDENTITY"
                : $" GENERATED BY DEFAULT AS IDENTITY (START WITH {identity.StartValue} INCREMENT BY {identity.Increment})",
        _ => string.Empty,
    };

    /// <inheritdoc />
    public override string RenderForeignKeyActions(ReferentialAction onDelete, ReferentialAction onUpdate) => onDelete switch
    {
        ReferentialAction.Cascade => " ON DELETE CASCADE",
        ReferentialAction.SetNull => " ON DELETE SET NULL",
        _ => string.Empty,
    };

    /// <inheritdoc />
    public override string RenderGenerated(GeneratedColumn generated) =>
        $" GENERATED ALWAYS AS ({generated.Expression}) VIRTUAL";

    /// <inheritdoc />
    public override string? RenderDefault(DefaultValue value) => value.Kind switch
    {
        // Oracle has no TIME type or CURRENT_TIME.
        DefaultValueKind.CurrentTime => "CURRENT_TIMESTAMP",
        DefaultValueKind.Literal when value.Value is { } literal && literal.Equals("true", StringComparison.OrdinalIgnoreCase) => "1",
        DefaultValueKind.Literal when value.Value is { } literal && literal.Equals("false", StringComparison.OrdinalIgnoreCase) => "0",
        _ => base.RenderDefault(value),
    };

    [GeneratedRegex("^[A-Z][A-Z0-9_$#]*$")]
    private static partial Regex PlainName();

    [GeneratedRegex("^[A-Za-z][A-Za-z0-9_$#]*$")]
    private static partial Regex FoldableName();
}
